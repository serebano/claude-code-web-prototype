import type {CSSProperties, HTMLAttributes} from 'react';
import './icons.css';

// Names and code points are observed in the installed Claude renderer; see docs/ICON-AUDIT.md.
type IconProps = HTMLAttributes<HTMLElement> & {size?: number; strokeWidth?: number};
function icon(name: string, codePoint: number) {
  return function Icon({size = 20, className = '', style, strokeWidth: _strokeWidth, ...props}: IconProps) {
    // Match the shipped renderer's optical-master/stroke-to-weight calculation.
    const closest = [12, 16, 20, 24, 28, 32].reduce((best, value) => Math.abs(value-size) <= Math.abs(best-size) ? value : best);
    const stroke = ({12: .8,16: 1,20: 1.2,24: 1.4,28: 1.6,32: 1.8} as Record<number, number>)[closest];
    const master = size <= 18 ? 16 : 20;
    const [lo, hi] = master === 16 ? [.8, 1.25] : [1.125, 1.8];
    const weight = Math.round(Math.max(400, Math.min(700, 400 + 300 * ((stroke * master / size - lo) / (hi - lo)))) * 10) / 10;
    return <i {...props} aria-hidden="true" data-icon={name} className={`claude-icon ${className}`} style={{'--icon-size': `${size}px`, fontWeight: weight, ...style} as CSSProperties}>{String.fromCodePoint(codePoint)}</i>;
  };
}
